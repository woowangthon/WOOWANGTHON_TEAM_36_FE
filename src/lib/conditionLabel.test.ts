import { conditionLabel } from './conditionLabel'

it.each([
  ['TOEIC 500점 이상', '어학 성적'],
  ['청주시에 1년 이상 주민등록이 되어 있는 자', '거주 기간'],
  ['휴학 예정·계획이 있는 학생 제외', '휴학 계획'],
  ['편입학 예정인 학생 지원 불가', '편입 계획'],
  ['대한민국 고등학교를 졸업한 자', '출신 학교'],
  ['타 장학금과 중복 수혜 불가', '신청 이력'],
  ['국가장학금을 신청하여야 함', '신청 이력'],
  ['농업·수산업 관련 학과 전공자', '전공'],
  ['고립·은둔 지원 프로그램을 수료한 자', '교육 이수'],
  ['미혼인 자', '기타 조건'],
])('%s → %s', (text, label) => {
  expect(conditionLabel(text)).toBe(label)
})
